# Find employee who got more avg selery then it dept and less then max of marketing dept
WITH AVGIT AS
(
	SELECT AVG(SALARY) AS SAL1 FROM EMPLOYEES
	WHERE DEPARTMENT_ID = 60
), 
MAXMKT AS
(
	SELECT MAX(SALARY) AS SAL2 FROM EMPLOYEES
	WHERE DEPARTMENT_ID = 20
)

SELECT * FROM EMPLOYEES
WHERE SALARY > (SELECT SAL1 FROM AVGIT) AND SALARY < (SELECT SAL2 FROM MAXMKT);