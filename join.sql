SELECT * FROM EMPLOYEES;
SELECT * FROM DEPARTMENTS;

# Joining Tables without using JOIN Query
SELECT EMPLOYEES.FIRST_NAME, DEPARTMENTS.DEPARTMENT_NAME
FROM EMPLOYEES, DEPARTMENTS
WHERE EMPLOYEES.DEPARTMENT_ID = DEPARTMENTS.DEPARTMENT_ID;

# Joining Tables with JOIN Query
SELECT EMPLOYEES.FIRST_NAME, DEPARTMENTS.DEPARTMENT_NAME
FROM EMPLOYEES
	JOIN DEPARTMENTS ON EMPLOYEES.DEPARTMENT_ID = DEPARTMENTS.DEPARTMENT_ID;


SELECT EMPLOYEES.FIRST_NAME, DEPARTMENTS.DEPARTMENT_NAME
FROM EMPLOYEES
	JOIN DEPARTMENTS USING(DEPARTMENT_ID);

# self join: employee first name + manager name
SELECT  man.FIRST_NAME AS EMPLOYEE, emp.FIRST_NAME AS MANAGER
FROM EMPLOYEES AS man
	JOIN EMPLOYEES AS emp
    ON emp.EMPLOYEE_ID = man.MANAGER_ID;
    
# find any of depertment where has no employee
SELECT DEPARTMENTS.DEPARTMENT_NAME
FROM DEPARTMENTS
	LEFT JOIN EMPLOYEES
		ON DEPARTMENTS.DEPARTMENT_ID = EMPLOYEES.DEPARTMENT_ID
WHERE EMPLOYEES.DEPARTMENT_ID IS NULL;

